import * as fs from "fs"
import { Writable } from "stream"
import { Type, Specification, ModuleDecl, Export } from "../idl-node"
import { filenamePrefix, filename, filenameLocal, hasValueType, FileType, writeIndent, writeDoc, operationDoc } from "../util"
import { typeIDLtoGIOPCC } from "./typeIDLtoGIOPCC"
import { Direction, typeIDLtoCC } from "./typeIDLtoCC"

export function writeCCInterface(specification: Specification): void {
    let out = fs.createWriteStream(filenamePrefix + ".hh")
    out.write("// This file is generated by the corba.js IDL compiler from '" + filename + "'.\n\n")
    out.write(`#pragma once\n`)
    out.write(`#include <corba/orb.hh>\n`)
    out.write(`#include <corba/giop.hh>\n`)
    out.write(`#include <corba/coroutine.hh>\n`)
    out.write(`#include <corba/corba.hh>\n`)
    out.write(`#include <memory>\n`)
    out.write(`#include <string>\n`)
    out.write(`#include <utility>\n`)
    out.write(`#include <vector>\n`)
    out.write(`#include <span>\n`)
    if (hasValueType(specification)) {
        out.write("import * as valuetype from \"./" + filenameLocal + "_valuetype\"\n")
    }
    out.write(`\n`)
    writeCCInterfaceDefinitions(out, specification)
}

export function writeCCInterfaceDefinitions(out: Writable, specification: Specification | ModuleDecl, prefix = "", indent = 0): void {
    for (let definition of specification.definitions) {
        switch (definition.type) {
            case Type.TKN_MODULE:
                out.write("namespace " + definition.name + " {\n\n")
                writeCCInterfaceDefinitions(out, definition, prefix + definition.name + "::", indent + 1)
                out.write("} // namespace " + definition.name + "\n\n")
                break

            case Type.SYN_INTERFACE: {
                let identifier = definition.name
                let inheritance_spec = definition.base?.name
                let interface_body = definition.body

                writeDoc(out, definition.doc, 0)
                out.write(`class ${identifier}: public virtual ${inheritance_spec?inheritance_spec:"CORBA::Object"} {\n`)
                out.write(`public:\n`)
                writeCCInterfaceBody(out, interface_body)
                out.write(`    std::string_view repository_id() const override;\n`)
                out.write(`    bool _is_a(const std::string_view &repository_id) const override;\n`);
                out.write(`    static std::shared_ptr<${identifier}> _narrow(std::shared_ptr<CORBA::Object> pointer);\n`)
                out.write("};\n\n")
            } break

            case Type.TKN_STRUCT: {
                let identifier = definition.name
                writeDoc(out, definition.doc, indent)
                // let value_header = value_dcl.child[0]!
                // let custom = value_header.child[0]
                // const member_list = struct_type.child[0]!.child[1]!.child!

                writeIndent(out, indent)
                out.write(`struct ${identifier} {\n`)

                for (const member of definition.members) {
                    for (let declarator of member.names) {
                        writeIndent(out, indent + 1)
                        out.write(
                            typeIDLtoCC(member.typeSpec, Direction.OUT) + " " + declarator + ";\n"
                        )
                        // attributes.push(declarator)
                    }
                }
                writeIndent(out, indent)
                out.write("};\n")
            } break

            case Type.TKN_UNION: {
                const identifier = definition.name
                const union_type = definition
                writeDoc(out, union_type.doc, indent)
                // unions with a default branch have no C++ mapping yet
                const cases = union_type.cases.map(x => {
                    if (x.type === Type.TKN_DEFAULT) {
                        throw Error("union default branch is not implemented yet")
                    }
                    return x
                })
                const switch_type = union_type.switchType.type === Type.SYN_SCOPED_NAME ? union_type.switchType.name : undefined
                let composite = ""
                cases.forEach(x => {
                    // console.log(x)
                    const case_label = x.label
                    const type_spec = x.typeSpec
                    const declarator = x.name
                    writeIndent(out, indent)
                    out.write(`export type _${identifier}_${declarator} = {\n`)
                    writeIndent(out, indent + 1)
                    out.write(`type: ${case_label.enum.name}.${case_label.name}\n`)
                    writeIndent(out, indent + 1)
                    out.write(`${declarator}: ${typeIDLtoCC(type_spec, Direction.IN)}\n`)
                    writeIndent(out, indent)
                    out.write(`}\n`)
                    if (composite.length !== 0)
                        composite = `${composite} | `
                    composite = `${composite}_${identifier}_${declarator}`
                })

                writeIndent(out, indent)
                out.write(`export type ${identifier} = ${composite}\n`)

                writeIndent(out, indent)
                out.write(`export function decode${identifier}(decoder: GIOPDecoder): ${identifier} {\n`)
                writeIndent(out, indent + 1)
                out.write(`switch(decoder.ulong() as ${switch_type}) {\n`) // FIXME: ulong is only valid for enums
                cases.forEach(x => {
                    const case_label = x.label
                    const type_spec = x.typeSpec
                    const declarator = x.name
                    writeIndent(out, indent + 2)
                    out.write(`case ${case_label.enum.name}.${case_label.name}: return {\n`)
                    writeIndent(out, indent + 3)
                    out.write(`type: ${case_label.enum.name}.${case_label.name},\n`)
                    writeIndent(out, indent + 3)
                    out.write(`${declarator}: ${typeIDLtoGIOPCC(type_spec, undefined, Direction.OUT)}\n`)
                    writeIndent(out, indent + 2)
                    out.write(`}\n`)
                })
                writeIndent(out, indent + 1)
                out.write(`}\n`)
                writeIndent(out, indent + 1)
                out.write(`throw Error("invalid union value")\n`)
                writeIndent(out, indent)
                out.write(`}\n`)

                writeIndent(out, indent)
                out.write(`export function encode${identifier}(encoder: GIOPEncoder, obj: ${identifier}) {\n`)
                writeIndent(out, indent + 1)
                out.write(`encoder.ulong(obj.type)\n`) // FIXME: ulong is only valid for enums
                writeIndent(out, indent + 1)
                out.write(`switch(obj.type) {\n`)
                cases.forEach(x => {
                    const case_label = x.label
                    const type_spec = x.typeSpec
                    const declarator = x.name
                    writeIndent(out, indent + 2)
                    out.write(`case ${case_label.enum.name}.${case_label.name}:\n`)
                    writeIndent(out, indent + 3)
                    out.write(typeIDLtoGIOPCC(type_spec, `obj.${declarator}`, Direction.OUT) + "\n")
                    writeIndent(out, indent + 3)
                    out.write(`break\n`)
                })
                writeIndent(out, indent + 1)
                out.write(`}\n`)
                out.write(`}\n\n`)
            } break

            case Type.TKN_ENUM: {
                const identifier = definition.name
                writeDoc(out, definition.doc, indent)
                writeIndent(out, indent)
                out.write(`enum class ${identifier} {\n`)
                for (const enumerator of definition.enumerators) {
                    writeIndent(out, indent + 1)
                    out.write(`${enumerator.name},\n`)
                }
                writeIndent(out, indent)
                out.write("};\n\n")
            } break
        }
    }
}

export function writeCCInterfaceBody(out: Writable, interface_body: Export[]) {
    for (let _export of interface_body) {
        switch (_export.type) {
            case Type.SYN_OPERATION_DECLARATION: {
                let op_dcl = _export
                writeDoc(out, operationDoc(op_dcl), 1)
                let type = op_dcl.returnType

                let oneway = op_dcl.oneway
                if (oneway && type.type !== Type.TKN_VOID)
                    throw Error("oneway methods must return void")

                let identifier = op_dcl.name
                let parameter_decls = op_dcl.params
                out.write("    virtual ")
                if (oneway) {
                    out.write(`${typeIDLtoCC(type, Direction.OUT)}`)
                } else {
                    out.write(`CORBA::async<${typeIDLtoCC(type, Direction.OUT)}>`)
                }
                out.write(` ${identifier}(`)
                let comma = false
                for (let parameter_dcl of parameter_decls) {
                    if (parameter_dcl.attribute !== Type.TKN_IN) {
                        throw Error("corba.js currently only supports 'in' parameters")
                    }
                    if (!comma) {
                        comma = true
                    } else {
                        out.write(", ")
                    }
                    out.write(`${typeIDLtoCC(parameter_dcl.typeSpec, Direction.IN)} ${parameter_dcl.name}`)
                }
                out.write(`) = 0;\n`)
            } break
            case Type.TKN_ATTRIBUTE: {
                const readonly = _export.readonly
                writeDoc(out, _export.doc, 1)
                const param_type_spec = _export.typeSpec
                for (const identifier of _export.names) {
                    out.write(`    virtual CORBA::async<${typeIDLtoCC(param_type_spec, Direction.OUT)}> ${identifier}() = 0;\n`)
                    if (!readonly) {
                        out.write(`    virtual CORBA::async<void> ${identifier}(${typeIDLtoCC(param_type_spec, Direction.IN)}) = 0;\n`)
                    }
                }
            } break
            default:
                throw Error("yikes")
        }
    }
}
