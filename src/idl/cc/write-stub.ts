import * as fs from "fs"
import { Type, Specification, ModuleDecl } from "../idl-node"
import { filenamePrefix, filename, filenameLocal, hasValueType, FileType } from "../util"
import { typeIDLtoGIOPCC } from "./typeIDLtoGIOPCC"
import { Direction, typeIDLtoCC } from "./typeIDLtoCC"

export function writeCCStub(specification: Specification): void {
    let out = fs.createWriteStream(filenamePrefix + "_stub.hh")
    out.write("// This file is generated by the corba.js IDL compiler from '" + filename + "'.\n\n")
    out.write(`#pragma once\n`)
    out.write(`#include <corba/corba.hh>\n`)
    out.write(`#include <corba/orb.hh>\n`)
    out.write(`#include <corba/giop.hh>\n`)
    out.write(`#include <corba/coroutine.hh>\n`)
    out.write(`#include <vector>\n`)
    if (hasValueType(specification)) {
        out.write("import * as valuetype from \"./" + filenameLocal + "_valuetype\"\n")
    }
    out.write(`#include "${filenameLocal}.hh"\n\n`)

    writeCCStubDefinitions(out, specification)
}
function writeCCStubDefinitions(out: fs.WriteStream, specification: Specification | ModuleDecl, prefix = "", indent = 0): void {
    for (let definition of specification.definitions) {
        switch (definition.type) {
            case Type.TKN_MODULE:
                out.write("namespace " + definition.name + " {\n\n")
                writeCCStubDefinitions(out, definition, prefix + definition.name + ".", indent + 1)
                out.write("} // namespace " + definition.name + "\n\n")
                break

            case Type.SYN_INTERFACE: {
                let identifier = definition.name
                let inheritance_spec = definition.base?.name
                let interface_body = definition.body

                out.write(`class ${identifier}_stub: public virtual ${prefix}${identifier}, public virtual ${inheritance_spec?inheritance_spec+"_stub":"CORBA::Stub"} {\n`)
                // out.write(`class ${identifier}_stub: public virtual ${prefix}${identifier}, public CORBA::Stub {\n`)
                out.write(`public:\n`)
                // out.write(`    ${identifier}_stub(std::shared_ptr<CORBA::ORB> orb, CORBA::blob_view objectKey, std::shared_ptr<CORBA::detail::Connection> connection): ${inheritance_spec?inheritance_spec+"_stub":"Stub"}(orb, objectKey, connection) {}\n`)

                for (let _export of interface_body) {
                    switch (_export.type) {
                        case Type.SYN_OPERATION_DECLARATION: {
                            let op_dcl = _export
                            let returnType = op_dcl.returnType

                            let oneway = op_dcl.oneway
                            if (oneway && returnType.type !== Type.TKN_VOID)
                                console.log("WARNING: corba.js currently requires every oneway function to return void")

                            let identifier = op_dcl.name
                            let parameter_decls = op_dcl.params

                            out.write("    virtual ")
                            if (oneway) {
                                out.write(`${typeIDLtoCC(returnType, Direction.OUT)}`)
                            } else {
                                out.write(`CORBA::async<${typeIDLtoCC(returnType, Direction.OUT)}>`)
                            }
                            out.write(` ${identifier}(`)
                            let comma = false
                            for (let parameter_dcl of parameter_decls) {
                                // TODO: move this check into the parser or attach file, row & col to the parse tree nodes
                                if (parameter_dcl.attribute !== Type.TKN_IN) {
                                    throw Error("corba.js currently only supports 'in' parameters")
                                }
                                if (!comma) {
                                    comma = true
                                } else {
                                    out.write(", ")
                                }
                                out.write(`${typeIDLtoCC(parameter_dcl.typeSpec, Direction.IN)} ${parameter_dcl.name}`)
                            }
                            out.write(`) override;\n`)
                        } break
                        case Type.TKN_ATTRIBUTE: {
                            const readonly = _export.readonly
                            const param_type_spec = _export.typeSpec
                            for(const identifier of _export.names) {
                                out.write(`    virtual CORBA::async<${typeIDLtoCC(param_type_spec, Direction.OUT)}> ${identifier}() override;\n`)
                                if (!readonly) {
                                    out.write(`    virtual CORBA::async<void> ${identifier}(${typeIDLtoCC(param_type_spec, Direction.IN)}) override;\n`)
                                }
                            }
                        } break
                        default:
                            throw Error("yikes")
                    }
                }
                out.write("};\n\n")
            } break
        }
    }
}
