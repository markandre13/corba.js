import * as fs from "fs"
import { Type, Specification, Definition, ValueTypeDecl } from "../idl-node"
import { filenamePrefix, filename, filenameLocal, hasNative, hasValueType, writeIndent, FileType, firstName, firstNode } from "../util"
import { typeIDLtoTS } from "./typeIDLtoTS"

export function writeTSValueImpl(specification: Specification): void {
    let out = fs.createWriteStream(filenamePrefix + "_valueimpl.ts")
    out.write(`// This file is generated by the corba.js IDL compiler from '${filename}'.\n\n`)
    out.write("import { ORB } from 'corba.js'\n")
    if (!hasValueType(specification)) {
        out.write("// no valuetype's defined in IDL")
        return
    }
    out.write(`import * as value from "./${filenameLocal}_value"\n\n`)
    out.write(`import * as valuetype from "./${filenameLocal}_valuetype"\n\n`)
    out.write(`import * as _interface from "./${filenameLocal}"\n\n`)

    if (hasNative(specification)) {
        out.write("declare global {\n")
        for (let definition of specification.definitions) {
            switch (definition.type) {
                case Type.TKN_NATIVE: {
                    let nativeName = definition.name
                    if (nativeName.length <= 4 ||
                        nativeName.substring(nativeName.length - 4) !== "_ptr") {
                        out.write("    interface " + nativeName + " {}\n")
                    }
                } break
            }
        }
        out.write("}\n\n")
    }

    writeTSValueImplDefinitions(out, specification.definitions)
}
function hasOperationDeclarations(value_dcl: ValueTypeDecl): boolean {
    for (let value_element of value_dcl.elements) {
        if (value_element.type === Type.SYN_OPERATION_DECLARATION) {
            return true
        }
    }

    if (value_dcl.base.length > 0) {
        const base = firstNode(value_dcl.base[0])
        if (base.type === Type.TKN_VALUETYPE) {
            if (hasOperationDeclarations(base)) {
                return true
            }
        }
    }

    return false
}
function writeTSValueImplDefinitions(out: fs.WriteStream, definitions: Definition[], prefix = "", indent = 0) {
    for (let definition of definitions) {
        switch (definition.type) {
            case Type.TKN_MODULE: {
                out.write("export namespace " + definition.name + " {\n\n")
                writeTSValueImplDefinitions(out, definition.definitions, prefix + definition.name + ".", indent + 1)
                out.write("} // namespace " + definition.name + "\n\n")
            } break
            case Type.TKN_NATIVE: {
            } break
            case Type.TKN_VALUETYPE: {
                let value_dcl = definition
                let identifier = value_dcl.name

                writeIndent(out, indent)
                out.write("export ")
                if (hasOperationDeclarations(value_dcl))
                    out.write("abstract ")

                else if (value_dcl.base.length > 0) { // FIXME: this works only over one inheritance level, make it recursive
                    const base = firstNode(value_dcl.base[0])
                    if (base.type === Type.TKN_VALUETYPE) {
                        if (hasOperationDeclarations(base))
                            out.write("abstract ")
                    }
                }
                out.write("class " + identifier)
                if (value_dcl.base.length > 0) {
                    if (value_dcl.base.length > 1)
                        throw Error("multiple inheritance is not supported for TypeScript")
                    out.write(" extends " + firstName(value_dcl.base[0]))
                }
                out.write(` implements valuetype.${prefix}${identifier} {\n`)

                for (let value_element of value_dcl.elements) {
                    if (value_element.type === Type.SYN_STATE_MEMBER) {
                        for (let declarator of value_element.names) {
                            writeIndent(out, indent + 1)
                            out.write(declarator + "!: " + typeIDLtoTS(value_element.typeSpec, FileType.VALUETYPE) + "\n")
                        }
                    }
                }

                out.write("\n")
                writeIndent(out, indent + 1)
                out.write(`constructor(init?: Partial<value.${prefix}${identifier}>) {\n`)
                if (value_dcl.base.length > 0) {
                    writeIndent(out, indent + 2)
                    out.write("super(init)\n")
                }
                writeIndent(out, indent + 2)
                out.write(`value.${prefix}init${identifier}(this, init)\n`)
                writeIndent(out, indent + 1)
                out.write("}\n")

                for (let value_element of value_dcl.elements) {
                    if (value_element.type === Type.SYN_OPERATION_DECLARATION) {
                        let op_decl = value_element
                        let op_identifier = op_decl.name
                        let parameter_decls = op_decl.params
                        writeIndent(out, indent + 1)
                        out.write("abstract ")
                        out.write(op_identifier + "(")
                        let comma = false
                        for (let parameter_dcl of parameter_decls) {
                            let param_identifier = parameter_dcl.name
                            if (parameter_dcl.attribute !== Type.TKN_IN) {
                                throw Error("corba.js currently only supports 'in' parameters")
                            }
                            if (comma) {
                                out.write(", ")
                            } else {
                                comma = true
                            }
                            out.write(param_identifier)
                            out.write(": ")
                            out.write(typeIDLtoTS(parameter_dcl.typeSpec))
                        }
                        out.write("): ")
                        out.write(typeIDLtoTS(op_decl.returnType))
                        out.write("\n")
                    }
                }
                writeIndent(out, indent)
                out.write("}\n\n")
            } break
        }
    }
}
