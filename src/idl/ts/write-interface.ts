import * as fs from "fs"
import { Type, Specification, Definition, Enumerator, SwitchCase, TypeSpec } from "../idl-node"
import { filenamePrefix, filename, filenameLocal, hasValueType, FileType, writeIndent, writtenName } from "../util"
import { typeIDLtoGIOPTS } from "./typeIDLtoGIOPTS"
import { typeIDLtoTS } from "./typeIDLtoTS"

export function writeTSInterface(specification: Specification): void {
    let out = fs.createWriteStream(filenamePrefix + ".ts")
    out.write("// This file is generated by the corba.js IDL compiler from '" + filename + "'.\n\n")
    out.write(`import { ORB, GIOPDecoder, GIOPEncoder } from 'corba.js'\n`)
    if (hasValueType(specification)) {
        out.write("import * as valuetype from \"./" + filenameLocal + "_valuetype\"\n\n")
    }
    writeTSInterfaceDefinitions(out, specification.definitions)
}

// a union case label is an enumerator, 'default' has no label
function caseLabel(switchCase: SwitchCase): Enumerator {
    if (switchCase.type !== Type.TKN_CASE)
        throw Error("'default' is not supported in union")
    return switchCase.label
}

// the switch type as the generated code names it
function switchTypeName(switchType: TypeSpec): string | undefined {
    switch (switchType.type) {
        case Type.SYN_SCOPED_NAME:
            return writtenName(switchType)
        case Type.TKN_ENUM:
            return switchType.name
        default:
            return undefined
    }
}

function writeTSInterfaceDefinitions(out: fs.WriteStream, definitions: Definition[], prefix = "", indent = 0): void {
    for (let definition of definitions) {
        switch (definition.type) {
            case Type.TKN_MODULE:
                out.write("export namespace " + definition.name + " {\n\n")
                writeTSInterfaceDefinitions(out, definition.definitions, prefix + definition.name + ".", indent + 1)
                out.write("} // namespace " + definition.name + "\n\n")
                break

            case Type.SYN_INTERFACE: {
                let interface_dcl = definition
                let identifier = interface_dcl.name
                let inheritance_spec = interface_dcl.base === undefined ? undefined : writtenName(interface_dcl.base)
                let interface_body = interface_dcl.body

                out.write(`export interface ${identifier}`)
                if (inheritance_spec) {
                    out.write(` extends ${inheritance_spec}`)
                }
                out.write(` {\n`)
                for (let _export of interface_body) {
                    switch (_export.type) {
                        case Type.SYN_OPERATION_DECLARATION: {
                            let op_dcl = _export
                            let oneway = op_dcl.oneway
                            if (oneway && op_dcl.returnType.type !== Type.TKN_VOID)
                                throw Error("oneway methods must return void")

                            let identifier = op_dcl.name
                            let parameter_decls = op_dcl.params
                            out.write("    ")
                            out.write(identifier + "(")
                            let comma = false
                            for (let parameter_dcl of parameter_decls) {
                                let identifier = parameter_dcl.name
                                if (parameter_dcl.attribute !== Type.TKN_IN) {
                                    throw Error("corba.js currently only supports 'in' parameters")
                                }
                                if (!comma) {
                                    comma = true
                                } else {
                                    out.write(", ")
                                }
                                out.write(identifier + ": " + typeIDLtoTS(parameter_dcl.typeSpec, FileType.INTERFACE))
                            }
                            if (oneway) {
                                out.write(`): ${typeIDLtoTS(op_dcl.returnType, FileType.INTERFACE)}\n`)
                            } else {
                                out.write(`): Promise<${typeIDLtoTS(op_dcl.returnType, FileType.INTERFACE)}>\n`)
                            }
                        } break
                        case Type.TKN_ATTRIBUTE: {
                            const readonly = _export.readonly
                            const type = typeIDLtoTS(_export.typeSpec, FileType.INTERFACE)
                            for (const identifier of _export.names) {
                                if (!readonly) {
                                    out.write(`    ${identifier}(value: ${type}): Promise<void>\n`)
                                }
                                out.write(`    ${identifier}(): Promise<${type}>\n`)
                            }
                        } break
                        default:
                            throw Error("yikes")
                    }
                }
                out.write("}\n\n")
            } break

            case Type.TKN_STRUCT: {
                let struct_type = definition
                let identifier = struct_type.name

                writeIndent(out, indent)
                out.write(`export interface ${identifier} {\n`)

                for (const member of struct_type.members) {
                    for (const declarator of member.names) {
                        writeIndent(out, indent + 1)
                        out.write(declarator + ": " + typeIDLtoTS(member.typeSpec, FileType.INTERFACE) + "\n")
                    }
                }
                writeIndent(out, indent)
                out.write("}\n")

                out.write(`export function decode${identifier}(decoder: GIOPDecoder): ${identifier} {\n`)
                out.write(`    return {\n`)
                for (const member of struct_type.members) {
                    for (const declarator of member.names) {
                        writeIndent(out, indent + 2)
                        out.write(declarator + ": " + typeIDLtoGIOPTS(member.typeSpec) + ",\n")
                    }
                }
                out.write(`    }\n`)
                out.write(`}\n`)
                out.write(`export function encode${identifier}(encoder: GIOPEncoder, obj: ${identifier}) {\n`)
                for (const member of struct_type.members) {
                    for (const declarator of member.names) {
                        writeIndent(out, indent + 1)
                        out.write(typeIDLtoGIOPTS(member.typeSpec, `obj.${declarator}`) + "\n")
                    }
                }
                out.write(`}\n\n`)
            } break

            case Type.TKN_UNION: {
                const identifier = definition.name
                const union_type = definition
                const switch_body = union_type.cases
                let composite = ""
                for (const x of switch_body) {
                    const case_label = caseLabel(x)
                    const type_spec = x.typeSpec
                    const declarator = x.name
                    writeIndent(out, indent)
                    out.write(`export type _${identifier}_${declarator} = {\n`)
                    writeIndent(out, indent + 1)
                    out.write(`type: ${case_label.enum.name}.${case_label.name}\n`)
                    writeIndent(out, indent + 1)
                    out.write(`${declarator}: ${typeIDLtoTS(type_spec, FileType.INTERFACE)}\n`)
                    writeIndent(out, indent)
                    out.write(`}\n`)
                    if (composite.length !== 0)
                        composite = `${composite} | `
                    composite = `${composite}_${identifier}_${declarator}`
                }

                writeIndent(out, indent)
                out.write(`export type ${identifier} = ${composite}\n`)

                writeIndent(out, indent)
                out.write(`export function decode${identifier}(decoder: GIOPDecoder): ${identifier} {\n`)
                writeIndent(out, indent + 1)
                out.write(`switch(decoder.ulong() as ${switchTypeName(union_type.switchType)}) {\n`) // FIXME: ulong is only valid for enums
                for (const x of switch_body) {
                    const case_label = caseLabel(x)
                    const type_spec = x.typeSpec
                    const declarator = x.name
                    writeIndent(out, indent + 2)
                    out.write(`case ${case_label.enum.name}.${case_label.name}: return {\n`)
                    writeIndent(out, indent + 3)
                    out.write(`type: ${case_label.enum.name}.${case_label.name},\n`)
                    writeIndent(out, indent + 3)
                    out.write(`${declarator}: ${typeIDLtoGIOPTS(type_spec, undefined, FileType.INTERFACE)}\n`)
                    writeIndent(out, indent + 2)
                    out.write(`}\n`)
                }
                writeIndent(out, indent + 1)
                out.write(`}\n`)
                writeIndent(out, indent + 1)
                out.write(`throw Error("invalid union value")\n`)
                writeIndent(out, indent)
                out.write(`}\n`)

                writeIndent(out, indent)
                out.write(`export function encode${identifier}(encoder: GIOPEncoder, obj: ${identifier}) {\n`)
                writeIndent(out, indent + 1)
                out.write(`encoder.ulong(obj.type)\n`) // FIXME: ulong is only valid for enums
                writeIndent(out, indent + 1)
                out.write(`switch(obj.type) {\n`)
                for (const x of switch_body) {
                    const case_label = caseLabel(x)
                    const type_spec = x.typeSpec
                    const declarator = x.name
                    writeIndent(out, indent + 2)
                    out.write(`case ${case_label.enum.name}.${case_label.name}:\n`)
                    writeIndent(out, indent + 3)
                    out.write(typeIDLtoGIOPTS(type_spec, `obj.${declarator}`, FileType.INTERFACE) + "\n")
                    writeIndent(out, indent + 3)
                    out.write(`break\n`)
                }
                writeIndent(out, indent + 1)
                out.write(`}\n`)
                out.write(`}\n\n`)
            } break

            case Type.TKN_ENUM: {
                const identifier = definition.name
                writeIndent(out, indent)
                out.write(`export enum ${identifier} {\n`)
                for (const enumerator of definition.enumerators) {
                    writeIndent(out, indent + 1)
                    out.write(`${enumerator.name},\n`)
                }
                writeIndent(out, indent)
                out.write("}\n\n")
            } break
        }
    }
}
